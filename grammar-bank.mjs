function fill(id, sentence, blankRomaji, options, answer, romaji, ko, explanation) {
  const pairs = options.map(option => option.split('|'));
  const choices = pairs.map(([japanese]) => japanese);
  return {
    id, sentence, blankRomaji, choices, answer, romaji, ko, explanation,
    choiceRomaji: pairs.map(([, pronunciation]) => pronunciation),
    complete: sentence[0] + choices[answer] + sentence[1]
  };
}

